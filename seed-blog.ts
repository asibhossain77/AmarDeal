async function main() {
  console.log(`🌱 Seeding ${posts.length} blog posts...`)

  for (const post of posts) {
    try {
      const created = await prisma.blogPost.create({
        data: {
          title: post.title,
          slug: post.slug,
          excerpt: post.excerpt,
          content: post.content.trim(),
          published: post.published,
        },
      })
      console.log(`  ✅ "${created.title}" (${created.slug})`)
    } catch (error: unknown) {
      const msg = error instanceof Error ? error.message : String(error)
      if (msg.includes('Unique')) {
        console.log(`  ⏭️  Skipping "${post.title}" — slug already exists`)
      } else {
        console.error(`  ❌ Error creating "${post.title}":`, msg)
      }
    }
  }

  const total = await prisma.blogPost.count({ where: { published: true } })
  console.log(`\n🎉 Done! Total published posts: ${total}`)
}

